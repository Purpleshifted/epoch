/**
 * qr.ts — a QR code for a short text (the recording's address on the specimen card), with no library: byte mode,
 * the smallest version that holds it, Reed–Solomon error correction, the mask with the lowest penalty. The method
 * follows the standard as laid out in Project Nayuki's QR Code generator (MIT). Returns the modules as rows of
 * booleans (true = dark), without the quiet zone; `qrSvgPath` turns them into one SVG path.
 */

export type QrEcc = "L" | "M" | "Q" | "H";

const ECC_ORDER: Record<QrEcc, number> = { L: 0, M: 1, Q: 2, H: 3 };
const FORMAT_BITS: Record<QrEcc, number> = { L: 1, M: 0, Q: 3, H: 2 };

